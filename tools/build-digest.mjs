/**
 * Builds catalog/digest.md: a fixed-budget overview of the catalog for agents.
 * For every category, the five best entries by quality (icons left out, one entry per
 * name, at most two per source so the overview spans sources), one line each. Deterministic: no timestamps, stable ordering.
 * `find.mjs` and `get.mjs` stay the detail layer.
 *
 * Usage: node tools/build-digest.mjs [--out <file>]   (default: ai-frontend-guide-kit/catalog/digest.md)
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CATALOG_DIR = join(ROOT, 'ai-frontend-guide-kit', 'catalog');
const PER_CATEGORY = 5;
const PER_SOURCE = 2;

function parseArgs(argv) {
  const flags = {};
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--out' && argv[i + 1]) flags.out = argv[++i];
    else throw new Error(`unknown argument "${argv[i]}" (usage: node tools/build-digest.mjs [--out <file>])`);
  }
  return flags;
}

function loadEntries() {
  const dir = join(CATALOG_DIR, 'sources');
  const entries = [];
  for (const file of readdirSync(dir).filter((name) => name.endsWith('.json')).sort()) {
    entries.push(...JSON.parse(readFileSync(join(dir, file), 'utf8')).entries);
  }
  return entries.filter((entry) => entry.entry_type !== 'icon');
}

const license = (entry) => (entry.commercial_use === false ? `${entry.license_type} (non-commercial)` : entry.license_type ?? 'unknown');

export function buildDigest() {
  const byCategory = new Map();
  for (const entry of loadEntries()) {
    if (!byCategory.has(entry.category)) byCategory.set(entry.category, []);
    byCategory.get(entry.category).push(entry);
  }
  const lines = [
    '# Catalog digest',
    '',
    `Generated by \`tools/build-digest.mjs\`; do not edit by hand. The ${PER_CATEGORY} best entries per category by quality (icons left out, at most ${PER_SOURCE} per source), one line each: \`id\` · source · license · quality · stack. For detail run \`node tools/get.mjs <id>\`; for more options, \`node tools/find.mjs --category <category>\`.`,
  ];
  for (const category of [...byCategory.keys()].sort()) {
    const all = byCategory.get(category).sort((a, b) => (b.quality ?? 0) - (a.quality ?? 0) || a.id.localeCompare(b.id));
    const seen = new Set();
    const perSource = new Map();
    const top = [];
    for (const entry of all) {
      const key = entry.name.toLowerCase();
      if (seen.has(key) || (perSource.get(entry.source) ?? 0) >= PER_SOURCE) continue;
      seen.add(key);
      perSource.set(entry.source, (perSource.get(entry.source) ?? 0) + 1);
      top.push(entry);
      if (top.length === PER_CATEGORY) break;
    }
    lines.push('', `## ${category}`, '', `${all.length} entries.`, '');
    for (const entry of top) {
      lines.push(`- \`${entry.id}\` · ${entry.source} · ${license(entry)} · q${entry.quality ?? '-'} · ${(entry.stack ?? []).slice(0, 2).join(', ') || '—'}`);
    }
  }
  return `${lines.join('\n')}\n`;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const flags = parseArgs(process.argv.slice(2));
  const out = flags.out ? resolve(flags.out) : join(CATALOG_DIR, 'digest.md');
  const text = buildDigest();
  writeFileSync(out, text, 'utf8');
  console.log(`digest: ${Buffer.byteLength(text)} bytes written to ${out}`);
}
